/** Search emojis by query: keywords or category id, else return recent + first category. */
export function searchEmojis(query: string): string[] {
  const q = query.trim().toLowerCase();
  if (!q) return [];
  const fromKeyword = SEARCH_KEYWORDS[q];
  if (fromKeyword) return fromKeyword;
  const category = EMOJI_CATEGORIES.find(
    (c) => c.id !== 'recent' && c.label.toLowerCase().includes(q),
  );
  if (category && category.id !== 'recent') return EMOJI_BY_CATEGORY[category.id].slice(0, 48);
  return ALL_EMOJIS.filter((e) => e === q).slice(0, 48);
}
