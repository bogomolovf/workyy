const RECENT_STORAGE_KEY = 'workyy-comment-recent-emojis';
const RECENT_MAX = 32;

export function getRecentEmojis(): string[] {
  if (typeof window === 'undefined') return [];
  try {
    const raw = localStorage.getItem(RECENT_STORAGE_KEY);
    if (!raw) return [];
    const parsed = JSON.parse(raw) as unknown;
    return Array.isArray(parsed) ? parsed.slice(0, RECENT_MAX) : [];
  } catch {
    return [];
  }
}

export function addToRecentEmojis(emoji: string): void {
  if (typeof window === 'undefined') return;
  try {
    const recent = getRecentEmojis().filter((e) => e !== emoji);
    recent.unshift(emoji);
    localStorage.setItem(RECENT_STORAGE_KEY, JSON.stringify(recent.slice(0, RECENT_MAX)));
  } catch {
    // ignore
  }
}

export function clearRecentEmojis(): void {
  if (typeof window === 'undefined') return;
  try {
    localStorage.removeItem(RECENT_STORAGE_KEY);
  } catch {
    // ignore
  }
}

